-- Drop in reverse dependency order (safe to re-run)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('APPT_AUDIT','BILL','PRESCRIPTION','MEDICINE',
                                 'APPOINTMENT','PATIENT','DOCTOR','DEPARTMENT'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE department (
  dept_id     NUMBER(5)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_name   VARCHAR2(40)  NOT NULL UNIQUE,
  location    VARCHAR2(40)  NOT NULL
);

CREATE TABLE doctor (
  doctor_id        NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  doctor_name      VARCHAR2(50)  NOT NULL,
  dept_id          NUMBER(5)     NOT NULL REFERENCES department(dept_id),
  specialization   VARCHAR2(50)  NOT NULL,
  consult_fee      NUMBER(8,2)   NOT NULL CHECK (consult_fee > 0),
  phone            VARCHAR2(15)  NOT NULL UNIQUE,
  max_daily_slots  NUMBER(2)     DEFAULT 16 NOT NULL CHECK (max_daily_slots BETWEEN 1 AND 16)
);

CREATE TABLE patient (
  patient_id     NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_name   VARCHAR2(50)  NOT NULL,
  dob            DATE          NOT NULL,
  gender         CHAR(1)       NOT NULL CHECK (gender IN ('M','F','O')),
  phone          VARCHAR2(15)  NOT NULL UNIQUE,
  email          VARCHAR2(80)  UNIQUE,
  registered_on  DATE          DEFAULT SYSDATE NOT NULL
);

CREATE TABLE appointment (
  appt_id     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id  NUMBER(8)     NOT NULL REFERENCES patient(patient_id),
  doctor_id   NUMBER(6)     NOT NULL REFERENCES doctor(doctor_id),
  appt_date   DATE          NOT NULL,
  slot_no     NUMBER(2)     NOT NULL CHECK (slot_no BETWEEN 1 AND 16),
  status      VARCHAR2(10)  DEFAULT 'BOOKED' NOT NULL
                            CHECK (status IN ('BOOKED','COMPLETED','CANCELLED','NO_SHOW')),
  booked_on   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

-- A doctor's slot may be held by only ONE active (non-cancelled) appointment.
-- Cancelled rows map to NULL keys, which Oracle does not index, so a cancelled
-- slot can be re-booked.
CREATE UNIQUE INDEX ux_appt_active_slot ON appointment (
  CASE WHEN status <> 'CANCELLED' THEN doctor_id END,
  CASE WHEN status <> 'CANCELLED' THEN appt_date END,
  CASE WHEN status <> 'CANCELLED' THEN slot_no   END
);

CREATE INDEX ix_appt_patient_date ON appointment (patient_id, appt_date);

CREATE TABLE medicine (
  med_id         NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  med_name       VARCHAR2(60)  NOT NULL UNIQUE,
  unit_price     NUMBER(8,2)   NOT NULL CHECK (unit_price >= 0),
  stock_qty      NUMBER(6)     DEFAULT 0 NOT NULL CHECK (stock_qty >= 0),
  reorder_level  NUMBER(6)     DEFAULT 20 NOT NULL CHECK (reorder_level >= 0)
);

CREATE TABLE prescription (
  appt_id   NUMBER(10)    NOT NULL REFERENCES appointment(appt_id),
  med_id    NUMBER(6)     NOT NULL REFERENCES medicine(med_id),
  quantity  NUMBER(4)     NOT NULL CHECK (quantity > 0),
  dosage    VARCHAR2(40)  NOT NULL,
  CONSTRAINT pk_prescription PRIMARY KEY (appt_id, med_id)
);

CREATE TABLE bill (
  bill_id         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appt_id         NUMBER(10)    NOT NULL UNIQUE REFERENCES appointment(appt_id),
  consult_amt     NUMBER(10,2)  NOT NULL CHECK (consult_amt >= 0),
  med_amt         NUMBER(10,2)  DEFAULT 0 NOT NULL CHECK (med_amt >= 0),
  gst_rate        NUMBER(4,2)   DEFAULT 5 NOT NULL CHECK (gst_rate BETWEEN 0 AND 28),
  payment_status  VARCHAR2(6)   DEFAULT 'UNPAID' NOT NULL CHECK (payment_status IN ('UNPAID','PAID')),
  generated_on    DATE          DEFAULT SYSDATE NOT NULL,
  paid_on         DATE,
  CONSTRAINT chk_paid_on CHECK (
    (payment_status = 'PAID' AND paid_on IS NOT NULL) OR
    (payment_status = 'UNPAID' AND paid_on IS NULL))
);

CREATE TABLE appt_audit (
  audit_id    NUMBER(10)    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  appt_id     NUMBER(10)    NOT NULL,
  old_status  VARCHAR2(10),
  new_status  VARCHAR2(10)  NOT NULL,
  changed_on  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  changed_by  VARCHAR2(30)  DEFAULT USER NOT NULL
);
